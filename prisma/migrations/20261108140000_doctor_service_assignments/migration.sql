  `doctorId` CHAR(36) NOT NULL,
  `serviceId` CHAR(36) NOT NULL,
  `facilityId` CHAR(36) NOT NULL,
  `branchId` CHAR(36) NULL,
  `scopeType` ENUM('FACILITY', 'BRANCH') NOT NULL,
  `scopeId` CHAR(36) NOT NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

  PRIMARY KEY (`tenantId`, `doctorId`, `serviceId`, `scopeType`, `scopeId`),
  INDEX `DoctorServiceAssignment_tenant_doctor_location_idx`
    (`tenantId`, `doctorId`, `facilityId`, `branchId`),
  INDEX `DoctorServiceAssignment_tenant_service_location_idx`
    (`tenantId`, `serviceId`, `facilityId`, `branchId`),

  CONSTRAINT `DoctorServiceAssignment_tenant_fkey`
    FOREIGN KEY (`tenantId`) REFERENCES `Tenant` (`id`)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `DoctorServiceAssignment_doctor_tenant_fkey`
    FOREIGN KEY (`doctorId`, `tenantId`) REFERENCES `Doctor` (`id`, `tenantId`)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `DoctorServiceAssignment_service_tenant_fkey`
    FOREIGN KEY (`serviceId`, `tenantId`) REFERENCES `Service` (`id`, `tenantId`)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `DoctorServiceAssignment_facility_tenant_fkey`
    FOREIGN KEY (`facilityId`, `tenantId`) REFERENCES `Facility` (`id`, `tenantId`)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `DoctorServiceAssignment_branch_facility_fkey`
    FOREIGN KEY (`branchId`, `facilityId`) REFERENCES `Branch` (`id`, `facilityId`)
    ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
